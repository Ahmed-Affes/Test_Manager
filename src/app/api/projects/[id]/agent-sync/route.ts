import { NextResponse } from 'next/server';
import { createClient } from '@/lib/supabase/server';
import { createAdminClient } from '@/lib/supabase/admin';

export async function POST(
  request: Request,
  { params }: { params: Promise<{ id: string }> }
) {
  try {
    const { id } = await params;
    const body = await request.json();
    const admin = createAdminClient();

    // 1. Resolve project by UUID or Key
    const isUuid = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(id);
    let projQuery = admin.from('projects').select('*');
    if (isUuid) {
      projQuery = projQuery.eq('id', id);
    } else {
      projQuery = projQuery.ilike('key', id);
    }
    const { data: project, error: projErr } = await projQuery.single();

    if (projErr || !project) {
      return NextResponse.json({ error: 'Project not found' }, { status: 404 });
    }

    const {
      suite: suiteName = 'AI Generated Tests',
      suite_description = 'Automated test suite generated by AI agent',
      tests = [],
      environment_name = 'Automated CI / Agent',
    } = body;

    if (!Array.isArray(tests) || tests.length === 0) {
      return NextResponse.json(
        { error: 'Invalid payload: tests must be a non-empty array' },
        { status: 400 }
      );
    }

    // 2. Resolve or create suite
    let suiteId: string | null = null;
    const { data: existingSuites } = await admin
      .from('test_suites')
      .select('id, name')
      .eq('project_id', project.id)
      .ilike('name', suiteName.trim());

    if (existingSuites && existingSuites.length > 0) {
      suiteId = existingSuites[0].id;
    } else {
      const { data: newSuite, error: suiteCreateErr } = await admin
        .from('test_suites')
        .insert({
          project_id: project.id,
          name: suiteName.trim(),
          description: suite_description,
          status: 'active',
        })
        .select()
        .single();

      if (!suiteCreateErr && newSuite) {
        suiteId = newSuite.id;
      }
    }

    // 3. Resolve or create environment
    let envId: string | null = null;
    const { data: existingEnvs } = await admin
      .from('environments')
      .select('id, name')
      .eq('project_id', project.id)
      .ilike('name', environment_name.trim());

    if (existingEnvs && existingEnvs.length > 0) {
      envId = existingEnvs[0].id;
    } else {
      const { data: newEnv } = await admin
        .from('environments')
        .insert({
          project_id: project.id,
          name: environment_name.trim(),
          runtime: 'AI Agent Runtime',
        })
        .select()
        .single();
      if (newEnv) envId = newEnv.id;
    }

    const results = {
      created_cases: 0,
      updated_cases: 0,
      created_runs: 0,
      details: [] as any[],
    };

    // 4. Process each test case
    for (let i = 0; i < tests.length; i++) {
      const item = tests[i];
      const testTitle = item.title || `Test Case ${i + 1}`;
      // Generate or use specified key
      const testKey = item.key || `${project.key}-${String(i + 1).padStart(3, '0')}`;

      // Check if test case already exists by key
      let caseId: string | null = null;
      const { data: existingCase } = await admin
        .from('test_cases')
        .select('id')
        .eq('project_id', project.id)
        .eq('key', testKey)
        .maybeSingle();

      if (existingCase) {
        caseId = existingCase.id;
        results.updated_cases++;
      } else {
        const { data: newCase, error: caseErr } = await admin
          .from('test_cases')
          .insert({
            project_id: project.id,
            suite_id: suiteId,
            key: testKey,
            title: testTitle,
            description: item.description || null,
            priority: item.priority || 'medium',
            severity: item.severity || 'major',
            type: item.type || 'automated',
            preconditions: item.preconditions || null,
            expected_result: item.expected_result || 'Expected behavior verified',
            status: 'active',
          })
          .select()
          .single();

        if (caseErr || !newCase) {
          console.warn('Failed to insert test case:', caseErr?.message);
          continue;
        }

        caseId = newCase.id;
        results.created_cases++;

        // Insert steps if provided
        if (Array.isArray(item.steps) && item.steps.length > 0) {
          const stepInserts = item.steps.map((st: any, idx: number) => ({
            test_case_id: caseId,
            step_number: idx + 1,
            action: typeof st === 'string' ? st : st.action || `Execute step ${idx + 1}`,
            expected_result: typeof st === 'object' ? st.expected || st.expected_result : null,
          }));
          await admin.from('test_steps').insert(stepInserts);
        }
      }

      // 5. If test execution run data is provided, record immutable run
      if (item.run && caseId) {
        const runStatus = item.run.status || 'pass';
        const { data: testRun, error: runErr } = await admin
          .from('test_runs')
          .insert({
            project_id: project.id,
            test_case_id: caseId,
            environment_id: envId,
            status: runStatus,
            duration_ms: item.run.duration_ms || 100,
            actual_result: item.run.actual_result || null,
            notes: item.run.notes || 'Executed via AI Agent sync',
            application_version: item.run.version || 'v1.0.0',
            branch: item.run.branch || 'main',
            commit_sha: item.run.commit_sha || null,
          })
          .select()
          .single();

        if (!runErr && testRun) {
          results.created_runs++;

          // If failed, optionally log issue
          if (runStatus === 'fail' && item.create_defect !== false) {
            const issueKey = `BUG-${project.key}-${String(results.created_runs).padStart(3, '0')}`;
            await admin.from('issues').insert({
              project_id: project.id,
              test_case_id: caseId,
              test_run_id: testRun.id,
              issue_key: issueKey,
              title: `[AI Defect] ${testTitle} failed`,
              description: item.run.actual_result || 'Automated execution failure detected by AI agent.',
              severity: item.severity || 'major',
              priority: 'high',
              status: 'open',
            });
          }
        }
      }

      results.details.push({ key: testKey, title: testTitle, case_id: caseId });
    }

    return NextResponse.json({
      success: true,
      project: { id: project.id, key: project.key, name: project.name },
      summary: results,
    });
  } catch (err: any) {
    console.error('Agent sync error:', err);
    return NextResponse.json({ error: err.message || 'Internal server error' }, { status: 500 });
  }
}
