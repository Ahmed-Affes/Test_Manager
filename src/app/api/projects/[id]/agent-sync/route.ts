import { NextResponse } from 'next/server';
import { createAdminClient } from '@/lib/supabase/admin';

export async function POST(
  request: Request,
  { params }: { params: Promise<{ id: string }> }
) {
  try {
    const { id } = await params;
    const body = await request.json();
    const admin = createAdminClient();

    // 1. Resolve project by UUID or Key (e.g. TM-101)
    const isUuid = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(id);
    let projQuery = admin.from('projects').select('*');
    if (isUuid) {
      projQuery = projQuery.eq('id', id);
    } else {
      projQuery = projQuery.ilike('key', id);
    }
    const { data: project, error: projErr } = await projQuery.single();

    if (projErr || !project) {
      return NextResponse.json({ error: 'Project not found' }, { status: 404 });
    }

    const {
      suite: suiteName = 'AI Generated Tests',
      suite_description = 'Automated test suite generated by AI agent',
      environment: envParam,
      environment_name: envNameFallback = 'Automated CI / Agent',
      plan: planParam,
      tests = [],
      issues: standaloneIssues = [],
      signoff: signoffParam,
    } = body;

    const summary = {
      suite: null as string | null,
      environment: null as string | null,
      plan: null as string | null,
      created_cases: 0,
      updated_cases: 0,
      created_runs: 0,
      created_issues: 0,
      attached_evidence: 0,
      signoff_recorded: false,
      details: [] as any[],
    };

    // 2. Resolve or create Suite
    let suiteId: string | null = null;
    if (suiteName) {
      const { data: existingSuites } = await admin
        .from('test_suites')
        .select('id, name')
        .eq('project_id', project.id)
        .ilike('name', suiteName.trim());

      if (existingSuites && existingSuites.length > 0) {
        suiteId = existingSuites[0].id;
      } else {
        const { data: newSuite } = await admin
          .from('test_suites')
          .insert({
            project_id: project.id,
            name: suiteName.trim(),
            description: suite_description,
            status: 'active',
          })
          .select()
          .single();

        if (newSuite) suiteId = newSuite.id;
      }
      summary.suite = suiteName;
    }

    // 3. Resolve or create Environment
    let envId: string | null = null;
    const envObj = typeof envParam === 'object' && envParam !== null ? envParam : null;
    const finalEnvName = (envObj?.name || (typeof envParam === 'string' ? envParam : envNameFallback)).trim();

    if (finalEnvName) {
      const { data: existingEnvs } = await admin
        .from('environments')
        .select('id, name')
        .eq('project_id', project.id)
        .ilike('name', finalEnvName);

      if (existingEnvs && existingEnvs.length > 0) {
        envId = existingEnvs[0].id;
      } else {
        const { data: newEnv } = await admin
          .from('environments')
          .insert({
            project_id: project.id,
            name: finalEnvName,
            os: envObj?.os || 'Linux x86_64',
            cpu: envObj?.cpu || null,
            ram: envObj?.ram || null,
            runtime: envObj?.runtime || 'AI Agent Execution Harness',
            description: envObj?.description || 'Automated agent target environment',
          })
          .select()
          .single();
        if (newEnv) envId = newEnv.id;
      }
      summary.environment = finalEnvName;
    }

    // 4. Resolve or create Test Plan (if provided)
    let planId: string | null = null;
    const planObj = typeof planParam === 'object' && planParam !== null ? planParam : null;
    const finalPlanName = (planObj?.name || (typeof planParam === 'string' ? planParam : null))?.trim();

    if (finalPlanName) {
      const { data: existingPlans } = await admin
        .from('test_plans')
        .select('id, name')
        .eq('project_id', project.id)
        .ilike('name', finalPlanName);

      if (existingPlans && existingPlans.length > 0) {
        planId = existingPlans[0].id;
      } else {
        const { data: newPlan } = await admin
          .from('test_plans')
          .insert({
            project_id: project.id,
            name: finalPlanName,
            description: planObj?.description || 'AI agent milestone verification plan',
            status: 'in_progress',
          })
          .select()
          .single();
        if (newPlan) planId = newPlan.id;
      }
      summary.plan = finalPlanName;
    }

    // 5. Process Test Cases & Runs
    const processedCaseIds: string[] = [];

    if (Array.isArray(tests)) {
      for (let i = 0; i < tests.length; i++) {
        const item = tests[i];
        const testTitle = item.title || `Test Case ${i + 1}`;
        const testKey = item.key || `${project.key}-${String(i + 1).padStart(3, '0')}`;
        const expectedOverall = item.expected_result || item.steps?.[0]?.expected || 'Expected behavior verified';

        let caseId: string | null = null;
        const { data: existingCase } = await admin
          .from('test_cases')
          .select('id')
          .eq('project_id', project.id)
          .eq('key', testKey)
          .maybeSingle();

        if (existingCase) {
          caseId = existingCase.id;
          summary.updated_cases++;

          await admin
            .from('test_cases')
            .update({
              title: testTitle,
              description: item.description || null,
              priority: item.priority || 'medium',
              severity: item.severity || 'major',
              type: item.type || 'automated',
              preconditions: item.preconditions || null,
              expected_result: expectedOverall,
              status: item.status || 'active',
              updated_at: new Date().toISOString(),
            })
            .eq('id', caseId);
        } else {
          const { data: newCase, error: caseErr } = await admin
            .from('test_cases')
            .insert({
              project_id: project.id,
              suite_id: suiteId,
              key: testKey,
              title: testTitle,
              description: item.description || null,
              priority: item.priority || 'medium',
              severity: item.severity || 'major',
              type: item.type || 'automated',
              preconditions: item.preconditions || null,
              expected_result: expectedOverall,
              status: item.status || 'active',
            })
            .select()
            .single();

          if (caseErr || !newCase) {
            console.warn('Failed to insert test case:', caseErr?.message);
            continue;
          }

          caseId = newCase.id;
          summary.created_cases++;

          // Insert steps
          if (Array.isArray(item.steps) && item.steps.length > 0) {
            const stepInserts = item.steps.map((st: any, idx: number) => ({
              test_case_id: caseId,
              step_number: idx + 1,
              action: typeof st === 'string' ? st : st.action || `Execute step ${idx + 1}`,
              expected_result: typeof st === 'object' ? st.expected || st.expected_result : null,
              notes: typeof st === 'object' ? st.notes : null,
            }));
            await admin.from('test_steps').insert(stepInserts);
          }
        }

        if (caseId) {
          processedCaseIds.push(caseId);

          // Link to Test Plan if active
          if (planId) {
            await admin
              .from('test_plan_items')
              .upsert({ test_plan_id: planId, test_case_id: caseId }, { onConflict: 'test_plan_id,test_case_id' });
          }

          // 6. Record Execution Run
          if (item.run) {
            const runStatus = item.run.status || 'pass';
            const { data: testRun, error: runErr } = await admin
              .from('test_runs')
              .insert({
                project_id: project.id,
                test_case_id: caseId,
                environment_id: envId,
                status: runStatus,
                duration_ms: item.run.duration_ms || 120,
                actual_result: item.run.actual_result || null,
                notes: item.run.notes || 'Executed via AI Agent sync',
                application_version: item.run.version || 'v1.0.0',
                branch: item.run.branch || 'main',
                commit_sha: item.run.commit_sha || null,
              })
              .select()
              .single();

            if (!runErr && testRun) {
              summary.created_runs++;

              // Record Step Results if provided
              if (Array.isArray(item.run.step_results) && item.run.step_results.length > 0) {
                const stepResults = item.run.step_results.map((sr: any, sIdx: number) => ({
                  test_run_id: testRun.id,
                  step_number: sr.step_number || sIdx + 1,
                  status: sr.status || 'pass',
                  actual_result: sr.actual_result || null,
                  notes: sr.notes || null,
                }));
                await admin.from('test_step_results').insert(stepResults);
              }

              // Evidence attachment
              if (Array.isArray(item.run.evidence) && item.run.evidence.length > 0) {
                for (const ev of item.run.evidence) {
                  await admin.from('evidence').insert({
                    project_id: project.id,
                    test_case_id: caseId,
                    test_run_id: testRun.id,
                    original_file_name: ev.file_name || 'agent_log.txt',
                    file_path: ev.file_path || `agent-artifacts/${Date.now()}-${ev.file_name || 'log.txt'}`,
                    file_type: ev.file_type || 'text/plain',
                    file_size: ev.file_size || 1024,
                    description: ev.description || 'Execution output log from AI agent',
                  });
                  summary.attached_evidence++;
                }
              }

              // If test execution failed, create linked issue
              if (runStatus === 'fail' && item.create_defect !== false) {
                const issueKey = `BUG-${project.key}-${String(summary.created_runs).padStart(3, '0')}`;
                const defect = item.defect || {};
                await admin.from('issues').insert({
                  project_id: project.id,
                  test_case_id: caseId,
                  test_run_id: testRun.id,
                  issue_key: issueKey,
                  title: defect.title || `[Defect] ${testTitle} failed`,
                  description:
                    defect.description ||
                    item.run.actual_result ||
                    'Automated execution failure detected during agent test run.',
                  severity: defect.severity || item.severity || 'major',
                  priority: defect.priority || item.priority || 'high',
                  status: defect.status || 'open',
                  root_cause: defect.root_cause || null,
                  fix_description: defect.fix_description || null,
                  related_commit: item.run.commit_sha || null,
                });
                summary.created_issues++;
              }
            }
          }

          summary.details.push({ key: testKey, title: testTitle, case_id: caseId });
        }
      }
    }

    // 7. Process Standalone Issues (if provided)
    if (Array.isArray(standaloneIssues) && standaloneIssues.length > 0) {
      for (const iss of standaloneIssues) {
        const issKey = iss.key || `BUG-${project.key}-${Date.now().toString().slice(-4)}`;
        await admin.from('issues').upsert(
          {
            project_id: project.id,
            issue_key: issKey,
            title: iss.title || 'Standalone Defect',
            description: iss.description || null,
            severity: iss.severity || 'major',
            priority: iss.priority || 'medium',
            status: iss.status || 'open',
            root_cause: iss.root_cause || null,
            fix_description: iss.fix_description || null,
            related_commit: iss.related_commit || null,
            resolution: iss.resolution || null,
          },
          { onConflict: 'project_id,issue_key' }
        );
        summary.created_issues++;
      }
    }

    // 8. Process Quality Sign-Off (if requested)
    if (signoffParam && signoffParam.decision) {
      await admin.from('report_signoffs').insert({
        project_id: project.id,
        role: signoffParam.role || 'Automated AI Verification Gate',
        decision: signoffParam.decision, // 'approved' | 'rejected' | 'conditional'
        notes: signoffParam.notes || 'Automated sign-off recorded by AI Agent sync',
      });
      summary.signoff_recorded = true;
    }

    // 9. Record project audit event
    await admin.from('audit_logs').insert({
      project_id: project.id,
      action: 'agent_sync',
      entity_type: 'project',
      entity_id: project.id,
      metadata: {
        suite: summary.suite,
        environment: summary.environment,
        plan: summary.plan,
        created_cases: summary.created_cases,
        updated_cases: summary.updated_cases,
        created_runs: summary.created_runs,
        created_issues: summary.created_issues,
      },
    });

    return NextResponse.json({
      success: true,
      project: { id: project.id, key: project.key, name: project.name },
      summary,
    });
  } catch (err: any) {
    console.error('Agent sync error:', err);
    return NextResponse.json({ error: err.message || 'Internal server error' }, { status: 500 });
  }
}
